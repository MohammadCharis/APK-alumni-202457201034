    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        // TODO add your handling code here:
        String NIP = tNIP.getText();
        String namaGuru = tNamaGuru.getText();
        String jenisKelamin = cJenisKelamin.getSelectedItem().toString();
        String alamat = tAlamat.getText();
        String jK = null;
        
        if (cJenisKelamin.getSelectedItem() != null) {
            jK = cJenisKelamin.getSelectedItem().toString();
        } else {
            JOptionPane.showMessageDialog(null, "Jenis kelamin belum dipilih!");
          return;
        }
        
        String sql = "INSERT INTO guru(nip, nama_guru, gander, alamat) VALUES (?,?,?,?)";
        
        try {
            Connection conn = koneksi.konek();
            PreparedStatement ps = conn.prepareStatement(sql);
            
            ps.setString(1, NIP);
            ps.setString(2, namaGuru);
            ps.setString(3, jK);
            ps.setString(4, alamat);
            ps.execute();
            
            JOptionPane.showMessageDialog(null, "Data berhasil disimpan!");
        } catch (SQLException sQLException) {
            
            JOptionPane.showMessageDialog(null, "Data gagal disimpan!");
        }
        
        load_tabel_guru();
        
        reset();
    }//GEN-LAST:event_btnTambahActionPerformed

